#!/usr/bin/env python3
"""Generate the promo's voice-over and music.

Reads script.json (each line's "text" is spoken; an optional "caption" is shown instead), speaks every line with Kokoro (Apache-2.0 text-to-speech, runs offline),
and writes ../src/voiceover/<id>.mp3 plus lines.ts with each clip's import and duration,
which the video uses to time its scenes. Also writes a short retro music bed (music.mp3).

    python3 -m venv .venv && .venv/bin/pip install kokoro-onnx soundfile numpy
    # model files (from https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0):
    #   kokoro-v1.0.onnx and voices-v1.0.bin, in this folder or in $KOKORO_DIR
    .venv/bin/python generate.py

Needs ffmpeg to encode MP3.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "voiceover"


def speak(script):
    from kokoro_onnx import Kokoro

    models = Path(os.environ.get("KOKORO_DIR", HERE))
    kokoro = Kokoro(str(models / "kokoro-v1.0.onnx"), str(models / "voices-v1.0.bin"))
    entries = []
    for line in script["lines"]:
        samples, rate = kokoro.create(line["text"], voice=script["voice"], speed=script["speed"], lang="en-us")
        samples = trim_silence(np.asarray(samples, dtype=np.float32), rate)
        mp3 = OUT / f"{line['id']}.mp3"
        encode(samples, rate, mp3)
        seconds = round(len(samples) / rate, 3)
        # Captions may be written differently from how they're spoken ("30,000" vs "thirty thousand").
        entries.append((line["id"], line.get("caption", line["text"]), seconds))
        print(f"{line['id']:10} {seconds:6.2f}s  {line['text'][:60]}")
    return entries


def trim_silence(samples, rate, threshold=0.01):
    loud = np.flatnonzero(np.abs(samples) > threshold)
    if not len(loud):
        return samples
    pad = int(0.05 * rate)
    return samples[max(0, loud[0] - pad) : loud[-1] + pad]


def encode(samples, rate, path):
    wav = path.with_suffix(".wav")
    sf.write(wav, samples, rate)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-b:a", "128k", str(path)], check=True)
    wav.unlink()


def music(seconds, path, rate=44100):
    """A soft chiptune bed: square-wave arpeggios over a triangle bass, Am–F–C–G at 100 BPM."""
    beat = 60 / 100
    step = beat / 4  # sixteenth notes
    chords = [(57, [69, 72, 76]), (53, [65, 69, 72]), (48, [64, 67, 72]), (55, [62, 67, 71])]  # bass, arpeggio (MIDI)
    freq = lambda n: 440 * 2 ** ((n - 69) / 12)
    n = int(seconds * rate)
    out = np.zeros(n, dtype=np.float32)
    t_step = int(step * rate)
    pattern = [0, 1, 2, 1]
    i = 0
    while i * t_step < n:
        bar = (i // 16) % len(chords)
        bass, arp = chords[bar]
        start = i * t_step
        length = min(t_step, n - start)
        t = np.arange(length) / rate
        env = np.exp(-t * 18)  # plucky
        note = arp[pattern[i % 4]] + (12 if (i // 4) % 4 == 3 else 0)
        sq = np.sign(np.sin(2 * np.pi * freq(note) * t)) * 0.10 * env
        out[start : start + length] += sq
        if i % 4 == 0:  # bass on every beat
            tb = np.arange(min(t_step * 4, n - start)) / rate
            tri = 2 / np.pi * np.arcsin(np.sin(2 * np.pi * freq(bass - 12) * tb)) * 0.22 * np.exp(-tb * 2.5)
            out[start : start + len(tri)] += tri
        if i % 8 == 0:  # soft kick
            tk = np.arange(min(int(0.12 * rate), n - start)) / rate
            kick = np.sin(2 * np.pi * (110 * np.exp(-tk * 30) + 40) * tk) * np.exp(-tk * 25) * 0.35
            out[start : start + len(kick)] += kick
        i += 1
    fade = int(2.5 * rate)
    out[-fade:] *= np.linspace(1, 0, fade)
    out[: int(0.5 * rate)] *= np.linspace(0, 1, int(0.5 * rate))
    out /= max(1e-9, np.abs(out).max()) / 0.8
    encode(out, rate, path)


def write_index(entries):
    lines = [
        "// Generated by marketing/voiceover/generate.py from script.json. Don't edit by hand.",
        *[f'import {i} from "./{i}.mp3";' for i, _, _ in entries],
        'import music from "./music.mp3";',
        "",
        "export type Line = { src: string; text: string; seconds: number };",
        "",
        "export const VOICE: Record<string, Line> = {",
        *[f"  {i}: {{ src: {i}, text: {json.dumps(text)}, seconds: {s} }}," for i, text, s in entries],
        "};",
        "",
        "export const MUSIC = music;",
        "",
    ]
    (OUT / "lines.ts").write_text("\n".join(lines))


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    script = json.loads((HERE / "script.json").read_text())
    entries = speak(script)
    total = sum(s for _, _, s in entries) + 25  # scenes add pauses around each line
    music(total, OUT / "music.mp3")
    write_index(entries)
    print(f"wrote {len(entries)} lines and music.mp3 to {OUT}", file=sys.stderr)
